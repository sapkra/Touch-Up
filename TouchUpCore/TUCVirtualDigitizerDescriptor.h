//  Research artifact, not yet compiled into any target.
//
//  The HID report descriptor Sidecar publishes for its virtual touchscreen,
//  extracted from /usr/libexec/SidecarDisplayAgent on macOS 27.0 (build 26A428):
//
//      xxd -p /usr/libexec/SidecarDisplayAgent | tr -d '\n' \
//          | grep -oE '050d0904a101.{0,1200}'
//
//  It appears twice, once per architecture slice, identically. This is the shape
//  the AppleMultitouchHIDService (0x0D,0x04) personality accepts — the personality
//  whose match dictionary requires Manufacturer == "Apple".
//
//  Descriptor: 256 bytes. Report: 81 bytes, report ID 5, laid out as
//
//      byte  0        report ID (5)
//      bytes 1-5      finger 1: 5-bit transducer index (usage 0x38), 1 bit pad,
//                     touch + in-range flags (0x33, 0x32), 16-bit X, 16-bit Y
//      bytes 6-10     finger 2: as above but a 4-bit index and 2 bits of padding
//      byte  11       contact count (usage 0x54), logical max 8
//      bytes 12-13    relative scan time (usage 0x56)
//      bytes 14-76    63-byte vendor blob, usage page 0xFF1A usage 0x11
//      bytes 77-78    vendor page 0xFF1A usage 0xE0F4, 2 bytes
//      bytes 79-80    vendor page 0xFF1A usages 0xE062..0xE068, 2 bits each
//
//  Two things follow. Contacts are reported through 0x38/0x33/0x32 rather than the
//  standard 0x51 ContactIdentifier / 0x42 TipSwitch, and the descriptor carries a
//  63-byte proprietary payload — so this is Apple's MT parser (parser-type 1,
//  parser-options 16), not a generic HID digitizer parser. A third-party panel's
//  ordinary Windows-style descriptor is not interchangeable with it.
//
//  Status: unusable so far. Publishing any virtual device requires the entitlement
//  com.apple.developer.hid.virtual.device, which AMFI treats as restricted: a binary
//  carrying it is SIGKILLed at launch unless a provisioning profile grants it. Ad-hoc
//  signing, Apple Development signing, and a sandboxed app bundle were all killed
//  (exit 137); the same binaries without the entitlement run and merely get NULL back
//  from IOHIDUserDeviceCreateWithProperties. The entitlement has to come from Apple
//  before this can be tested further.
//

